# tabs/income.py
import streamlit as st


def render():
    st.header("หมวดเงินได้พึงประเมิน 8 ประเภท")

    st.subheader("รายได้ประเภทที่ 1 (เงินเดือนและสวัสดิการ)")
    salary_mode = st.radio("รูปแบบการบันทึกข้อมูล", ["บันทึกเป็นรายปี", "คำนวณจากรายได้ต่อเดือน"], horizontal=True)

    if salary_mode == "คำนวณจากรายได้ต่อเดือน":
        col_m1, col_m2 = st.columns(2)
        with col_m1:
            monthly_salary = st.number_input("รายได้ประจำต่อเดือน (บาท)", min_value=0, step=1000)
        with col_m2:
            bonus = st.number_input("โบนัสและรายได้พิเศษอื่นๆ รวมทั้งปี (บาท)", min_value=0, step=5000)

        st.session_state.inc_40_1 = (monthly_salary * 12) + bonus
        st.info(f"ประมาณการรายได้ 40(1) รวมทั้งปี: **{st.session_state.inc_40_1:,.0f} บาท**")
    else:
        st.number_input(
            "40(1) เงินได้จากการจ้างแรงงาน (รวมทั้งปี)", min_value=0, step=10000,
            help="เช่น เงินเดือน โบนัส ค่าล่วงเวลา บำเหน็จบำนาญ",
            key='inc_40_1'
        )

    st.divider()
    st.subheader("รายได้ประเภทอื่นๆ")
    c1, c2 = st.columns(2)
    with c1:
        st.number_input("40(2) เงินได้จากหน้าที่หรือตำแหน่งงาน", min_value=0, step=10000,
            help="เช่น ค่านายหน้า ค่าธรรมเนียม ค่ารับทำงานอิสระเป็นครั้งคราว (หักค่าใช้จ่ายเหมา 50% รวมกับ 40(1) สูงสุด 100,000 บาท)",
            key='inc_40_2')

        st.number_input("40(3) ค่าแห่งกู๊ดวิลล์ ลิขสิทธิ์", min_value=0, step=10000,
            help="เช่น ค่าลิขสิทธิ์ สิทธิบัตร ทรัพย์สินทางปัญญา (หักค่าใช้จ่ายเหมา 50% สูงสุด 100,000 บาท สำหรับค่าลิขสิทธิ์)",
            key='inc_40_3')

        st.number_input("40(4) ดอกเบี้ย เงินปันผล และผลประโยชน์จากการลงทุน", min_value=0, step=10000,
            help="เช่น ดอกเบี้ยเงินฝาก เงินปันผล กำไรจากการขายคริปโทเคอร์เรนซี (กฎหมายไม่อนุญาตให้หักค่าใช้จ่าย)",
            key='inc_40_4')

    with c2:
        st.number_input("40(5) เงินได้จากการให้เช่าทรัพย์สิน", min_value=0, step=10000,
            help="เช่น การให้เช่าอาคาร บ้าน ที่ดิน รถยนต์ (หักค่าใช้จ่ายเหมา 10-30% ขึ้นอยู่กับประเภททรัพย์สิน)",
            key='inc_40_5')

        st.number_input("40(6) เงินได้จากวิชาชีพอิสระ", min_value=0, step=10000,
            help="เช่น ประกอบโรคศิลปะ (หักเหมา 60%) กฎหมาย วิศวกรรม สถาปัตยกรรม บัญชี (หักเหมา 30%)",
            key='inc_40_6')

        st.number_input("40(7) เงินได้จากการรับเหมา (ลงทุนด้วยสัมภาระ)", min_value=0, step=10000,
            help="ผู้รับเหมาที่ต้องจัดหาสัมภาระในส่วนสำคัญนอกจากเครื่องมือ (หักค่าใช้จ่ายเหมา 60% หรือหักตามเอกสารค่าใช้จ่ายจริง)",
            key='inc_40_7')

        st.number_input("40(8) เงินได้จากธุรกิจ พาณิชยกรรม หรืออื่นๆ", min_value=0, step=10000,
            help="เช่น ธุรกิจส่วนตัว ร้านอาหาร การเกษตร รวมถึงกำไรจากการเทรดสินทรัพย์ (หักค่าใช้จ่ายเหมา 60% หรือหักตามเอกสารค่าใช้จ่ายจริง)",
            key='inc_40_8')

        if st.session_state.inc_40_8 > 0:
            st.radio(
                "วิธีหักค่าใช้จ่ายสำหรับเงินได้ 40(8)",
                ["หักเหมา 60%", "หักตามจริง (ต้องมีเอกสารประกอบ)"],
                horizontal=True,
                key='mode_40_8'
            )

            if st.session_state.mode_40_8 == "หักตามจริง (ต้องมีเอกสารประกอบ)":
                st.number_input(
                    "ระบุค่าใช้จ่ายตามจริง (บาท)",
                    min_value=0,
                    max_value=int(st.session_state.inc_40_8),
                    step=1000,
                    help="หักได้สูงสุดไม่เกินรายได้ 40(8) ที่ระบุไว้",
                    key='actual_exp_40_8'
                )

    st.divider()
    st.number_input(
        "ภาษีหัก ณ ที่จ่ายสะสม (Withholding Tax)", min_value=0, step=1000,
        help="ยอดรวมภาษีที่ถูกหักล่วงหน้าตามหนังสือรับรองการหักภาษี ณ ที่จ่าย (50 ทวิ)",
        key='wht'
    )
